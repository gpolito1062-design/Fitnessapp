import assert from 'node:assert/strict';
import {suggestLift,suggestRun,suggestedCalories,conflicts} from './coach.ts';
assert.equal(suggestLift('Press','6–10',[]).confidence,'insufficient data');
const sets=[{date:'2026-11-08',exercise:'Press',set:1,weight:100,reps:10,rir:1},{date:'2026-11-08',exercise:'Press',set:2,weight:100,reps:10,rir:1}];
assert.equal(suggestLift('Press','6–10',sets).title,'Increase load');
assert.equal(suggestLift('Press','6–10',[{...sets[0],reps:8},sets[1]]).title,'Keep the load; add reps');
assert.equal(suggestRun([], 'long',2).confidence,'insufficient data');
assert.equal(suggestRun([{date:'2026-11-08',distance:6,minutes:70,effort:'Easy'}], 'quality',5).title,'Recovery-first adjustment');
assert.equal(suggestedCalories([],3600).confidence,'insufficient data');
assert.equal(conflicts('Wednesday','heavy legs',[{day:'Thursday',activity:'quality run'}]).length,1);
console.log('All coaching engine tests passed.');
